package if_else_blocks;

public class Logical_Operator_OR {
	
	public static void main(String[] args) {
		
		//OR logical operator
		
		int age=25;
		
		if(age<25 || age!=25) //while checking OR (||) condition, at least one criteria should match
		{
			System.out.println("He is boy");
		}
		else {
			System.out.println("She is girl");
		}
	}

}
