package if_else_blocks;

public class Logical_Operator_AND {
	
	//AND (&&)logical operator
	
	public static void main(String[] args) {
		
		int age=58;
		
		if(age==58 && age>=58) //In AND logical operator both condition should satisfy/match
		{
			System.out.println("A person is retired");
		}
		else {
			System.out.println("Invalid Statement");
		}
	}

}
