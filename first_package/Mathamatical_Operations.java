package first_package;

public class Mathamatical_Operations {
	
	public static void main(String[] args) //main method
	
	{
		//Addition
		
		int a1=10;
		int b1=10;
		int sum1=a1+b1;
		System.out.println("Addition = " + sum1);
		
		/*int=integer data-types (we can pass only numeric data/whole number)
		 * a1= variable (we can pass any value)
		 * b1=variable (we can pass any value)
		 */
				
		//Subtraction
		
		int a2=10;
		int b2=5;
		int sum2=a2-b2;
		System.out.println("Subtraction = " + sum2);
		
		//Multiplication
		
		int a3=25;
		int b3=4;
		int sum3=a3*b3;
		System.out.println("Multiplication = " + sum3);
		
		//Division
		
		int a4=500;
		int b4=100;
		int sum4=a4/b4;
		System.out.println("Division = " + sum4);
		
	}

}
