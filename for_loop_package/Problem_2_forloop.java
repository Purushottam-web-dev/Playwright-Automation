package for_loop_package;

public class Problem_2_forloop {
	
	public static void main(String[] args) {
		
		//print the stars

		        for (int i = 1; i <= 10; i++) {
		            for (int j = 1; j <= i; j++) {
		                System.out.print("*");
		            }
		            System.out.println();
		        }
		    }
}
